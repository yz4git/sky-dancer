import type { SkyDancerArcadeEnemyKind } from "./SkyDancerArcadeData";
import { skyDancerArcadeV24FlightProfile } from "./SkyDancerArcadeV24FlightDynamics";

export interface SkyDancerArcadeV25FlightState {
  x: number;
  y: number;
  vx: number;
  vy: number;
  bank: number;
  pitch: number;
  energy: number;
}

export interface SkyDancerArcadeV25ControlProfile {
  maxBank: number;
  maxPitch: number;
  rollRate: number;
  pitchRate: number;
  turnAcceleration: number;
  climbAcceleration: number;
  bankGain: number;
  pitchGain: number;
  energyRecovery: number;
  turnEnergyCost: number;
  climbEnergyCost: number;
}

export interface SkyDancerArcadeV25VisualAttitude {
  headingOffset: number;
  bank: number;
  pitchOffset: number;
}

const clamp = (value: number, min: number, max: number) => Math.max(min, Math.min(max, value));
const moveToward = (current: number, target: number, maxDelta: number) => {
  if (current < target) return Math.min(target, current + maxDelta);
  if (current > target) return Math.max(target, current - maxDelta);
  return target;
};

